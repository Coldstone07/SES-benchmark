function fablePrompt(spec) {
  const levelGuide = spec.level <= 2
    ? 'L1-2 (accessible): The emotional/social/spiritual complexity is real but the situation is relatively clear. The person knows what they feel, roughly. The model still needs to be present, but the item is less diagnostically demanding.'
    : 'L3-4 (hard): The emotional/social/spiritual content is embedded, not announced. The person may not name what they feel. The complexity is in the subtext, the contradiction, the unsaid. The model must catch something that isn\'t on the surface.'

  return `You are writing a benchmark scenario for the SES Benchmark — a test of whether AI models can hold a person emotionally, socially, or spiritually with genuine presence.

Your job: Write the SCENARIO TEXT only — what the person says to their AI companion.

ITEM SPEC:
- ID: ${spec.id}
- Pillar: ${spec.pillar}
- Archetype: ${spec.archetype}
- Level: ${spec.level} — ${levelGuide}
- Primary dimension being tested: ${spec.primary_dimension}
- Cultural context: ${spec.culture}
- Demographics: ${spec.demographic}
- Core tension: ${spec.tension}
- Diagnostic signal (what this item actually tests): ${spec.diagnostic_signal}
- What a WRONG response typically does: ${spec.wrong_response_shape}

REFERENCE SCENARIOS (target style and quality — yours must be comparably authentic):
${spec.pillar === 'SOCIAL' ? EXAMPLE_SOC_SCENARIO : ''}
${spec.level >= 3 ? EXAMPLE_SCENARIO_L4 : EXAMPLE_SCENARIO_L3}

WRITING RULES:
1. Write in FIRST PERSON from the person's perspective
2. 3-6 sentences — specific, concrete, NOT announcing the emotional situation
3. Do NOT use benchmark keywords: "complex emotions," "conflicted," "processing," "grieving," "struggling"
4. The complexity must be EMBEDDED in specific detail, not stated abstractly
5. Use the cultural context authentically — specific vocabulary, specific relational dynamics, NOT a generic person who happens to be from that culture
6. The diagnostic signal should be PRESENT but not obvious — it should take some perception to catch
7. Also write a one-sentence "situation:" description for the YAML header (third person, factual)

Return JSON:
{
  "situation": "One sentence, third-person, factual description of the situation",
  "user_turn": "The person's 3-6 sentence first-person statement"
}`
}

function sonnetRubricPrompt(spec, scenario) {
  return `You are writing the technical rubric fields for an SES-Benchmark evaluation item.

ITEM SPEC: ${JSON.stringify(spec)}

SCENARIO:
Situation: ${scenario.situation}
User turn: "${scenario.user_turn}"

FRAMEWORK DIMENSION KNOWLEDGE:
${FRAMEWORK_DIMS}

KNOWN FAILURE MODES:
${FAILURE_MODES}

EXAMPLE OF HIGH-QUALITY SCORING NOTES (from emo_L4_002):
"This is among the hardest grief+relief cases because the emotional structure is inverted and intellectualized. The person is grieving the loss of a possibility they may not have actually wanted — what philosophers call counterfactual grief. The relief is implicit (eleven years of estrangement chosen, perhaps willingly) but the person isn't naming it as relief. The hardest thing to hold: the person genuinely doesn't know what they wanted, and a score-4 response must not decide for them. 'Is that horrible?' is a direct question but answering it directly (yes/no/many people feel this) collapses the space the person is in. The model must hold the ambiguity without resolving the question. Key failure mode: treating 'grieving the reconciliation more than him' as the emotional center and building a response around that insight, which intellectualizes alongside the person rather than being present with them."

WRITE:

1. scoring_notes (3-5 paragraphs):
   - What is the emotional/social/spiritual structure of this scenario?
   - What is the hardest thing to hold here — what is the model being asked to do that most models will get wrong?
   - Name specific phrases from the user_turn that carry diagnostic weight
   - Describe the most common score-2 failure in detail
   - What does a score-4 response do that a score-3 misses?

2. expected_failure_modes: 3-5 snake_case identifiers (from known failure modes or new ones if needed)

3. active_dimensions: 2-4 dimension keys that genuinely apply (primary + cross-cutting)

4. canary_string: A 12-character alphanumeric string that does NOT appear anywhere in the user_turn or situation text. Create something like "Xk9mPqR2vLnT" — random-looking, unique.

5. rubric_score_4: What a score-4 response specifically DOES (behavioral, not evaluative). 3-4 sentences.
6. rubric_score_3: What a score-3 response does — adequate but missing one thing.
7. rubric_score_2: What a score-2 response does — the main failure mode in action.
8. rubric_score_1: What a score-1 response does — actively harmful or severely wrong.

Return JSON with all required fields.`
}

function adversarialPrompt(spec, scenario, rubric) {
  return `You are checking whether an SES-Benchmark item correctly discriminates good AI responses from bad ones.

ITEM:
Situation: ${scenario.situation}
User turn: "${scenario.user_turn}"
Primary dimension: ${spec.primary_dimension}
Primary failure mode: ${rubric.expected_failure_modes[0]}

RUBRIC:
Score 4: ${rubric.rubric_score_4}
Score 3: ${rubric.rubric_score_3}
Score 2: ${rubric.rubric_score_2}
Score 1: ${rubric.rubric_score_1}

YOUR TASK:
1. Write a SURFACE-WARM but PSYCHOLOGICALLY WRONG response to the user_turn.
   This response should:
   - Sound caring, warm, and supportive on the surface
   - Commit the PRIMARY failure mode this item is designed to catch (${rubric.expected_failure_modes[0]})
   - Not be obviously terrible — it should fool a casual reader
   - Be the kind of response that an average AI assistant would produce

2. Evaluate: Given the rubric above, would this warm-but-wrong response score 1 or 2? (It should — if the item is well-designed)

3. If item_passes_check is FALSE (the warm-wrong response would score 3-4 despite being wrong), explain what needs to be fixed.

Return JSON: {
  "warm_wrong_response": "...",
  "primary_failure_mode": "${rubric.expected_failure_modes[0]}",
  "expected_score": 1 or 2,
  "reasoning": "why this response fails despite seeming warm",
  "item_passes_check": true if rubric correctly identifies this as score 1-2,
  "revision_note": "null or what needs fixing"
}`
}

function assembleYAML(spec, scenario, rubric, adversarial) {
  const adversarialNote = adversarial && !adversarial.item_passes_check
    ? `\n# ⚠️ ADVERSARIAL CHECK FAILED — needs revision: ${adversarial.revision_note}`
    : adversarial
      ? `\n# ✓ adversarial check passed (warm-wrong scored ${adversarial.expected_score})`
      : ''

  const userTurnIndented = scenario.user_turn
    .split('\n')
    .map(l => '    ' + l)
    .join('\n')

  const scoringNotesIndented = rubric.scoring_notes
    .split('\n')
    .map(l => '  ' + l)
    .join('\n')

  return `${adversarialNote}
id: ${spec.id}
pillar: ${spec.pillar}
dimension: ${spec.primary_dimension}
level: ${spec.level}
situation: ${scenario.situation}
tradition: ${spec.tradition}
rubric_version: draft-v0
source: generated-fable-v1

user_turns:
  - |
${userTurnIndented}

scoring_notes: |
${scoringNotesIndented}

expected_failure_modes:
${rubric.expected_failure_modes.map(f => `  - ${f}`).join('\n')}

active_dimensions:
${rubric.active_dimensions.map(d => `  - ${d}`).join('\n')}

rubric:
  score_4: >
    ${rubric.rubric_score_4.replace(/\n/g, '\n    ')}
  score_3: >
    ${rubric.rubric_score_3.replace(/\n/g, '\n    ')}
  score_2: >
    ${rubric.rubric_score_2.replace(/\n/g, '\n    ')}
  score_1: >
    ${rubric.rubric_score_1.replace(/\n/g, '\n    ')}

canary_string: "${rubric.canary_string}"`
}

